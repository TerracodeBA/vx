// gitUpstream is a local git repository standing in for GitHub.
type gitUpstream struct {
	t   *testing.T
	dir string
	wt  *git.Worktree
	n   int
}

func newGitUpstream(t *testing.T) *gitUpstream {
	t.Helper()
	dir := t.TempDir()
	r, err := git.PlainInitWithOptions(dir, &git.PlainInitOptions{
		InitOptions: git.InitOptions{DefaultBranch: plumbing.NewBranchReferenceName("main")},
	})
	if err != nil {
		t.Fatal(err)
	}
	wt, err := r.Worktree()
	if err != nil {
		t.Fatal(err)
	}
	return &gitUpstream{t: t, dir: dir, wt: wt}
}

// commit writes files and commits them on main: another team's merged PR.
func (u *gitUpstream) commit(msg string, files map[string]string) string {
	u.t.Helper()
	for p, c := range files {
		full := filepath.Join(u.dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			u.t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(c), 0o644); err != nil {
			u.t.Fatal(err)
		}
		if _, err := u.wt.Add(p); err != nil {
			u.t.Fatal(err)
		}
	}
	u.n++
	h, err := u.wt.Commit(msg, &git.CommitOptions{Author: &gitobject.Signature{
		Name: "Bob", Email: "bob@example.com", When: time.Date(2026, 11, 1, 10, u.n, 0, 0, time.UTC),
	}})
	if err != nil {
		u.t.Fatal(err)
	}
	return h.String()
}

const genHeader = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage apiv1\n\n"

// TestEffortRebaseAfterAnotherEffortShipped reproduces the stuck v0.2
// effort: efforts A and B start from main, B ships (its commit lands on
// main), and A's ship plan conflicts until A is rebased.
func TestEffortRebaseAfterAnotherEffortShipped(t *testing.T) {
	up := newGitUpstream(t)
	up.commit("Initial", map[string]string{
		"api.proto":     "message Effort {\n  string slug = 1;\n}\n",
		"gen/api.pb.go": genHeader + "type Effort struct {\n\tSlug string\n}\n",
		"README.md":     "# shop\n",
	})
	h, aliceToken := newHarnessWith(t, true)
	work := t.TempDir()
	alice := h.user("alice", aliceToken, work)
	alice.must("repo", "create", "shop", "--git", up.dir)
	alice.must("effort", "new", "Effort A", "--repo", "shop")
	alice.must("effort", "new", "Effort B", "--repo", "shop")
	var agent struct{ Token string }
	if err := json.Unmarshal([]byte(alice.must("agent", "add", "worker", "--json")), &agent); err != nil {
		t.Fatal(err)
	}
	a := h.user("worker", agent.Token, work)
	a.must("clone", "shop", "effort-a", "a")
	a.dir = filepath.Join(work, "a")
	// A second working copy of effort A, with a workspace open across the rebase.
	b := h.user("worker-b", agent.Token, work)
	b.must("clone", "shop", "effort-a", "b")
	b.dir = filepath.Join(work, "b")

	a.must("new", "Add Effort.rebase")
	a.write("api.proto", "message Effort {\n  string slug = 1; // unique per repo\n  Rebase rebase = 2;\n}\n")
	a.write("gen/api.pb.go", genHeader+"type Effort struct {\n\tSlug   string // unique per repo\n\tRebase *Rebase\n}\n")
	a.write("rebase.go", "package shop\n")
	a.must("land", "--run", "true")
	a.must("new", "Document rebase")
	a.write("README.md", "# shop\n\nRebasing works.\n")
	a.must("land")
	before := a.must("log", "--json")

	b.must("sync")
	b.must("new", "Add notes")
	b.write("notes.md", "notes\n")

	// Effort B ships: its PR merges into main, touching the same lines.
	sha := up.commit("Rename Effort.slug to name (effort B)", map[string]string{
		"api.proto":     "message Effort {\n  string name = 1;\n}\n",
		"gen/api.pb.go": genHeader + "type Effort struct {\n\tName string\n}\n",
	})

	out, code := a.run("ship", "plan")
	if code != 2 || !strings.Contains(out, "conflicts with main") || !strings.Contains(out, "api.proto") {
		t.Fatalf("ship plan before the rebase: exit %d\n%s", code, out)
	}

	// Rebase: stops on the first change, with markers in the proto and the
	// effort's version in the generated file.
	out, code = a.run("effort", "rebase")
	if code != 2 {
		t.Fatalf("rebase should stop on the conflict: exit %d\n%s", code, out)
	}
	for _, want := range []string{"stopped at change", "Add Effort.rebase", "api.proto", "gen/api.pb.go (generated file: regenerate it (for example `buf generate`) instead of editing the markers", "vx effort rebase --continue", "vx effort rebase --abort"} {
		if !strings.Contains(out, want) {
			t.Errorf("rebase output lacks %q:\n%s", want, out)
		}
	}
	proto := a.read("api.proto")
	if !strings.Contains(proto, "<<<<<<< change ") || !strings.Contains(proto, "string name = 1;") || !strings.Contains(proto, "string slug = 1; // unique per repo") {
		t.Fatalf("api.proto should hold both sides with markers:\n%s", proto)
	}
	if got := a.read("gen/api.pb.go"); got != genHeader+"type Effort struct {\n\tSlug   string // unique per repo\n\tRebase *Rebase\n}\n" {
		t.Fatalf("generated file should be the effort's version, without markers:\n%s", got)
	}
	if a.read("rebase.go") != "package shop\n" {
		t.Fatal("the change's other files should be written too")
	}
	st := a.must("status")
	if !strings.Contains(st, "Rebasing onto main: stopped at change") || !strings.Contains(st, "Conflicts: api.proto, gen/api.pb.go") {
		t.Fatalf("status while rebasing:\n%s", st)
	}
	// Others see it too.
	if st := b.must("status"); !strings.Contains(st, "A rebase of this effort onto main by agent:alice/worker is stopped on a conflict at change") {
		t.Fatalf("status of another working copy:\n%s", st)
	}
	if out, code := a.run("land"); code == 0 || !strings.Contains(out, "in the middle of a rebase") {
		t.Fatalf("land while rebasing: exit %d\n%s", code, out)
	}
	if out, code := a.run("effort", "rebase"); code == 0 || !strings.Contains(out, "in the middle of a rebase") {
		t.Fatalf("second rebase: exit %d\n%s", code, out)
	}
	if out, code := a.run("effort", "rebase", "--continue"); code == 0 || !strings.Contains(out, "api.proto still has conflict markers") {
		t.Fatalf("continue with markers: exit %d\n%s", code, out)
	}

	// Resolve, regenerate, continue: the second change replays cleanly.
	a.write("api.proto", "message Effort {\n  string name = 1; // unique per repo\n  Rebase rebase = 2;\n}\n")
	a.write("gen/api.pb.go", genHeader+"type Effort struct {\n\tName   string // unique per repo\n\tRebase *Rebase\n}\n")
	out = a.must("effort", "rebase", "--continue")
	if !strings.Contains(out, "Rebased effort effort-a onto main at "+sha[:12]) || !strings.Contains(out, "2 change(s) replayed") {
		t.Fatalf("continue:\n%s", out)
	}
	if st := a.must("status"); strings.Contains(st, "Rebasing") || !strings.Contains(st, "No local changes.") {
		t.Fatalf("status after the rebase:\n%s", st)
	}
	if a.read("README.md") != "# shop\n\nRebasing works.\n" || !strings.Contains(a.read("api.proto"), "string name = 1; // unique per repo") {
		t.Fatal("working copy should be at the rebased head")
	}

	// Same change ids, in the same order.
	after := a.must("log", "--json")
	ids := func(js string) []string {
		var l struct {
			Changesets []struct {
				ChangeId string `json:"changeId"`
				Rebased  bool   `json:"rebased"`
			} `json:"changesets"`
		}
		if err := json.Unmarshal([]byte(js), &l); err != nil {
			t.Fatalf("%v: %s", err, js)
		}
		var out []string
		for _, c := range l.Changesets {
			out = append(out, c.ChangeId)
		}
		return out
	}
	if strings.Join(ids(before), ",") != strings.Join(ids(after), ",") || len(ids(after)) != 2 {
		t.Fatalf("change ids before %v, after %v", ids(before), ids(after))
	}

	// Ship plan is clean now.
	out = a.must("ship", "plan")
	if strings.Contains(out, "conflicts") {
		t.Fatalf("ship plan after the rebase:\n%s", out)
	}

	// The workspace opened before the rebase syncs onto the new head and lands.
	out = b.must("sync")
	if !strings.Contains(out, "your 1 local change(s) kept") {
		t.Fatalf("sync after the rebase:\n%s", out)
	}
	if b.read("notes.md") != "notes\n" || !strings.Contains(b.read("api.proto"), "string name = 1; // unique per repo") {
		t.Fatal("sync should keep the local edit and bring in the rebased effort")
	}
	b.must("land")
	if out := a.must("sync"); !strings.Contains(out, "Synced") {
		t.Fatalf("a sync: %s", out)
	}
	if a.read("notes.md") != "notes\n" {
		t.Fatal("the land after the rebase should be on the effort")
	}
}

func TestEffortRebaseAbortRestoresWorkingCopy(t *testing.T) {
	up := newGitUpstream(t)
	up.commit("Initial", map[string]string{"auth.go": "package auth\n\nfunc Login() {\n}\n"})
	h, aliceToken := newHarnessWith(t, true)
	work := t.TempDir()
	alice := h.user("alice", aliceToken, work)
	alice.must("repo", "create", "shop", "--git", up.dir)
	alice.must("effort", "new", "Effort A", "--repo", "shop")
	alice.must("clone", "shop", "effort-a", "a")
	alice.dir = filepath.Join(work, "a")
	alice.must("new", "Rename Login")
	alice.write("auth.go", "package auth\n\nfunc SignIn() {\n}\n")
	alice.must("land")
	up.commit("Rename Login upstream", map[string]string{"auth.go": "package auth\n\nfunc LogIn() {\n}\n"})

	alice.write("stray.txt", "x\n")
	if out, code := alice.run("effort", "rebase"); code == 0 || !strings.Contains(out, "1 local change(s)") {
		t.Fatalf("rebase with local changes: exit %d\n%s", code, out)
	}
	if err := os.Remove(filepath.Join(alice.dir, "stray.txt")); err != nil {
		t.Fatal(err)
	}
	if _, code := alice.run("effort", "rebase"); code != 2 {
		t.Fatalf("rebase should stop, exit %d", code)
	}
	if !strings.Contains(alice.read("auth.go"), "<<<<<<<") {
		t.Fatal("markers expected")
	}
	out := alice.must("effort", "rebase", "--abort")
	if !strings.Contains(out, "Aborted the rebase of effort-a; the effort is unchanged.") {
		t.Fatalf("abort:\n%s", out)
	}
	if got := alice.read("auth.go"); got != "package auth\n\nfunc SignIn() {\n}\n" {
		t.Fatalf("abort should restore the files, auth.go = %q", got)
	}
	if st := alice.must("status"); strings.Contains(st, "Rebasing") || !strings.Contains(st, "No local changes.") {
		t.Fatalf("status after abort:\n%s", st)
	}
	alice.must("new", "Still works")
	alice.write("b.go", "package auth\n")
	alice.must("land")
}
