// Overlap statuses.
const (
	OverlapClean    = "clean"    // no files changed by both
	OverlapShared   = "overlap"  // files changed by both, they merge cleanly
	OverlapConflict = "conflict" // shipping both would conflict
)

// Overlap is a forecast collision between two open efforts of a repository.
type Overlap struct {
	RepoName    string
	Effort      store.Effort // the caller's side
	Other       store.Effort
	OtherOwner  store.Principal
	Status      string
	SharedFiles []string
	Conflicts   []string
	Warnings    []engine.Warning // kind "rule" for vx.toml violations, "duplicate" for Go
	CheckedAt   time.Time
}

