// Overlap statuses.
const (
	OverlapClean    = "clean"    // no files changed by both
	OverlapShared   = "overlap"  // files changed by both, they merge cleanly
	OverlapConflict = "conflict" // shipping both would conflict
)

// Overlap is a forecast collision between two open efforts of a repository.
type Overlap struct {
	RepoName    string
	Effort      store.Effort // the caller's side
	Other       store.Effort
	OtherOwner  store.Principal
	Status      string
	SharedFiles []string
	Conflicts   []string
	Warnings    []engine.Warning // kind "rule" for vx.toml violations, "duplicate" for Go
	CheckedAt   time.Time
}

// SystemPrincipalHandle is the service principal that posts system notes.
const SystemPrincipalHandle = "vx"

// UniqueRule says that files matching Glob may not share the first group
// of Key (for example two migrations with the same number).
type UniqueRule = rules.Unique

// GeneratedRule says files matching Glob are generated by Command: vx never
// text-merges them and tells people to regenerate instead.
type GeneratedRule = rules.Generated

// Rules are a repository's vx.toml (see internal/rules).
type Rules = rules.Rules

// RulesFile is where a repository keeps its rules.
const RulesFile = rules.File

// WarningRule marks a warning about a vx.toml rule.
const WarningRule = rules.WarningRule

func v03NotImplemented() error {
	return errf(CodeUnavailable, "this part of v0.3 is not implemented yet")
}

// ParseRules parses vx.toml. Unknown keys, invalid globs and regular
// expressions are errors that say the line and what is wrong.
func ParseRules(data []byte) (Rules, error) {
	return rules.Parse(data)
}

// RulesAt returns the rules in vx.toml at the root of tree (none: empty
// Rules, no error).
func (s *Service) RulesAt(ctx context.Context, tree hash.Hash) (Rules, error) {
	return rules.At(ctx, s.Blobs, tree)
}

// CheckRules reports violations of rules in tree, limited to the paths
// changed between base and tree, as warnings of kind WarningRule.
func (s *Service) CheckRules(ctx context.Context, r Rules, base, tree hash.Hash) ([]engine.Warning, error) {
	return rules.Check(ctx, s.Blobs, r, base, tree)
}

