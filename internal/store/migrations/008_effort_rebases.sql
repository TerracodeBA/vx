-- Effort rebases: replaying an effort's changes onto a newer head of its
-- base branch. A rebase is running while the server replays, stopped when a
-- change conflicts and waits for someone to resolve it, and then done (the
-- effort head moved to the rebased chain) or aborted (the effort is
-- unchanged). At most one rebase per effort is running or stopped.
create table effort_rebases (
    id          uuid primary key default gen_random_uuid(),
    repo_id     uuid not null references repos on delete cascade,
    effort_id   uuid not null references efforts on delete cascade,
    state       text not null check (state in ('running', 'stopped', 'done', 'aborted')),
    onto_branch text not null,
    onto        bytea not null,                 -- target changeset the effort moves onto
    onto_git_sha text not null default '',
    old_base    bytea not null,                 -- effort base when the rebase started
    old_head    bytea not null,                 -- effort head when the rebase started
    seen_head   bytea not null,                 -- newest old-chain head whose changes are replayed or pending
    new_head    bytea not null,                 -- tip of the rebased chain so far
    replayed    jsonb not null default '[]',    -- [{"from": hex, "to": hex}], oldest first
    pending     jsonb not null default '[]',    -- old changesets still to replay, oldest first; when stopped the first is the conflicting one
    conflicts   jsonb,                          -- when stopped: the conflicting paths
    started_by  uuid not null references principals,
    updated_by  uuid not null references principals,
    version     bigint not null default 0,      -- compare-and-swap between continue, abort and finish
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create unique index effort_rebases_one_active on effort_rebases (effort_id) where state in ('running', 'stopped');
create index effort_rebases_effort on effort_rebases (effort_id, created_at);

-- A rebased change keeps its change id and creation time, so "the newest
-- changeset with this change id" needs a tiebreak: the one stored last.
alter table changesets add column seq bigint generated by default as identity;
